// Generates src/features/travel/worldMap.ts — projected SVG paths for every
// country, keyed to our ISO alpha-2 codes. Run once (or when the atlas
// changes): `node scripts/gen-worldmap.mjs`. Runtime ships only the emitted
// data + react-native-svg; d3-geo/topojson/world-atlas stay devDependencies.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/countries-110m.json");
const worldCountries = require("world-countries/countries.json");

const WIDTH = 800;
const HEIGHT = 400;

// Numeric ISO 3166-1 (ccn3) → alpha-2 (cca2), for matching atlas feature ids.
const numericToA2 = new Map();
for (const c of worldCountries) {
  if (c.ccn3 && c.cca2) numericToA2.set(parseInt(c.ccn3, 10), c.cca2.toUpperCase());
}

const fc = feature(topo, topo.objects.countries);
const projection = geoNaturalEarth1().fitExtent(
  [
    [2, 2],
    [WIDTH - 2, HEIGHT - 2],
  ],
  fc,
);
const path = geoPath(projection);

// Trim coordinate precision to 1 dp — plenty at this viewBox, far smaller file.
const round = (d) => d.replace(/-?\d+\.\d+/g, (m) => Number(m).toFixed(1));

const rows = [];
for (const f of fc.features) {
  const d = path(f);
  if (!d) continue;
  const code = numericToA2.get(parseInt(f.id, 10)) ?? null;
  rows.push({ code, d: round(d) });
}

const body = rows
  .map((r) => `  { code: ${r.code ? `"${r.code}"` : "null"}, d: "${r.d}" },`)
  .join("\n");

const ts = `// AUTO-GENERATED by scripts/gen-worldmap.mjs — do not edit by hand.
// Natural Earth projection of the 110m world atlas; \`code\` is ISO alpha-2
// (null for features with no matching country, e.g. disputed borders).

export const WORLD_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";

export type CountryPath = { code: string | null; d: string };

export const COUNTRY_PATHS: CountryPath[] = [
${body}
];
`;

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "features",
  "travel",
  "worldMap.ts",
);
writeFileSync(out, ts);
console.log(`wrote ${rows.length} country paths -> ${out}`);
