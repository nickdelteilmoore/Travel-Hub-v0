// Generates supabase/seed/airports.sql from mwgg/Airports (MIT licence,
// https://github.com/mwgg/Airports) — every airport with an IATA code, with its
// IANA timezone, which segment times are localised against.
//
//   node scripts/gen-airports.mjs [path/to/airports.json]
//
// Without a path it downloads the dataset. Airports in a country the countries
// seed doesn't know are skipped, since travel_airports.country_code is a
// foreign key.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const known = new Set(
  require("world-countries/countries.json")
    .map((c) => (c.cca2 ?? "").toUpperCase())
    .filter((c) => c.length === 2),
);

const SOURCE = "https://raw.githubusercontent.com/mwgg/Airports/master/airports.json";
const input = process.argv[2];
const data = input
  ? JSON.parse(readFileSync(input, "utf8"))
  : await (await fetch(SOURCE)).json();

const esc = (s) => String(s).replace(/'/g, "''");
const text = (s) => (s ? `'${esc(s)}'` : "null");
const num = (n) => (typeof n === "number" && Number.isFinite(n) ? String(n) : "null");

const byIata = new Map();
for (const a of Object.values(data)) {
  const iata = (a.iata ?? "").trim().toUpperCase();
  const country = (a.country ?? "").trim().toUpperCase();
  if (!/^[A-Z0-9]{3}$/.test(iata) || !a.tz || !known.has(country)) continue;
  // The dataset has a handful of duplicate IATA codes; keep the first.
  if (!byIata.has(iata)) byIata.set(iata, { ...a, iata, country });
}

const rows = [...byIata.values()]
  .sort((a, b) => a.iata.localeCompare(b.iata))
  .map((a) => {
    const icao = /^[A-Z0-9]{4}$/.test(a.icao ?? "") ? `'${a.icao}'` : "null";
    return `  ('${a.iata}', ${icao}, ${text(a.name)}, ${text(a.city)}, '${a.country}', '${esc(a.tz)}', ${num(a.lat)}, ${num(a.lon)})`;
  });

const sql = `-- Seed: airports with an IATA code. Generated by scripts/gen-airports.mjs from
-- mwgg/Airports — Copyright (c) 2014 mwgg, MIT licence
-- (https://github.com/mwgg/Airports/blob/master/LICENSE). Idempotent.
insert into public.travel_airports (iata, icao, name, city, country_code, tz, latitude, longitude) values
${rows.join(",\n")}
on conflict (iata) do update
  set icao = excluded.icao,
      name = excluded.name,
      city = excluded.city,
      country_code = excluded.country_code,
      tz = excluded.tz,
      latitude = excluded.latitude,
      longitude = excluded.longitude;
`;

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase", "seed", "airports.sql");
writeFileSync(out, sql);
console.log(`wrote ${rows.length} airports -> ${out}`);
