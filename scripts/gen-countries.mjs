// Generates supabase/seed/countries.sql from the `world-countries` dataset.
// Flag emoji are computed from the ISO alpha-2 code (regional indicators),
// so no large emoji block is ever emitted by hand.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const countries = require("world-countries/countries.json");

const SCHENGEN = new Set([
  "AT", "BE", "BG", "HR", "CZ", "DK", "EE", "FI", "FR", "DE",
  "GR", "HU", "IS", "IT", "LV", "LI", "LT", "LU", "MT", "NL",
  "NO", "PL", "PT", "RO", "SK", "SI", "ES", "SE", "CH",
]);

const flagOf = (cca2) =>
  String.fromCodePoint(
    ...[...cca2].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65),
  );

const esc = (s) => s.replace(/'/g, "''");

const rows = countries
  .filter((c) => c.cca2 && c.cca2.length === 2)
  .sort((a, b) => a.cca2.localeCompare(b.cca2))
  .map((c) => {
    const code = c.cca2.toUpperCase();
    const name = esc(c.name.common);
    const flag = flagOf(code);
    const schengen = SCHENGEN.has(code) ? "true" : "false";
    return `  ('${code}', '${name}', '${flag}', ${schengen})`;
  });

const sql = `-- Seed: ISO 3166-1 alpha-2 countries with flag emoji and Schengen flags.
-- Generated by scripts/gen-countries.mjs. Apply once to a fresh project
-- (SQL editor or \`supabase db push\`). Idempotent via ON CONFLICT.
insert into public.countries (code, name, flag_emoji, is_schengen) values
${rows.join(",\n")}
on conflict (code) do update
  set name = excluded.name,
      flag_emoji = excluded.flag_emoji,
      is_schengen = excluded.is_schengen;
`;

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "supabase",
  "seed",
  "countries.sql",
);
writeFileSync(out, sql);
console.log(`wrote ${rows.length} countries (${SCHENGEN.size} Schengen) -> ${out}`);
